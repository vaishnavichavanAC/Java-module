
public class CharAtIndex {

	public static void main(String[] args) {
	
		String str = "Java Exercise";
		
		System.out.println("Original String = " +str);
		
		char characterAt0= str.charAt(0);
		char characterAt10= str.charAt(10);
		
		System.out.println("The character at position 0 is " +characterAt0);
		System.out.println("The character at position 10 is " +characterAt10);
		
	}

}
