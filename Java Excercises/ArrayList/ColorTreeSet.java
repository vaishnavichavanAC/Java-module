
package org.Vaishnavi;

import java.util.TreeSet;

public class ColorTreeSet {
	

    public static void main(String[] args) {

        // Create a new TreeSet
        TreeSet<String> colors = new TreeSet<String>();

        // Add colors
        colors.add("PINK");
        colors.add("PURPLE");
        colors.add("GREEN");
        colors.add("BLACK");
        colors.add("YELLOW");

        // Print the TreeSet
        System.out.println("TreeSet of colors: " + colors);
    }
}

